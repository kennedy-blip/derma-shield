/** Alias index for fast offline parsing of an INCI list. */
export const ALIAS_INDEX = (() => {
  const map = new Map();
  for (const row of INGREDIENTS) {
    map.set(row.name.toLowerCase(), row);
    map.set(row.id, row);
    for (const a of row.aliases) map.set(a.toLowerCase(), row);
  }
  return map;
})();

/** Look up one INCI token (case/space tolerant). */
export function lookupIngredient(token) {
  const t = token.trim().toLowerCase().replace(/\s+/g, ' ');
  if (ALIAS_INDEX.has(t)) return ALIAS_INDEX.get(t);
  // longest-substring alias match, tolerant of parenthetical INCI text
  let best = null;
  let bestLen = 0;
  for (const [alias, row] of ALIAS_INDEX) {
    if (alias.length > bestLen && t.includes(alias)) {
      best = row;
      bestLen = alias.length;
    }
  }
  return best;
}
